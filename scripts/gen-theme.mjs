// npm i @material/material-color-utilities esbuild, then bundle and run with node.
// Generates Material 3 color tokens (light + dark) for each seed and
// per-show accent colors. Output: js/theme-data.js
import {
  argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, TonalPalette,
} from '@material/material-color-utilities';
import { writeFileSync } from 'node:fs';

const SEEDS = {
  emerald: '#2E7D32',
  scarlet: '#C62828',
  sky: '#1E88E5',
  violet: '#6750A4',
  amber: '#F9A825',
  rose: '#AD1457',
};

const SHOWS = {
  arrow: '#2E7D32',
  flash: '#D32F2F',
  supergirl: '#1E88E5',
  legends: '#7B1FA2',
  constantine: '#8D6E63',
  vixen: '#EF6C00',
  blacklightning: '#00ACC1',
  stargirl: '#00897B',
  ray: '#F9A825',
  batwoman: '#AD1457',
  supermanlois: '#3949AB',
};

const ROLES = {
  primary: s => s.primary, 'on-primary': s => s.onPrimary,
  'primary-container': s => s.primaryContainer, 'on-primary-container': s => s.onPrimaryContainer,
  secondary: s => s.secondary, 'on-secondary': s => s.onSecondary,
  'secondary-container': s => s.secondaryContainer, 'on-secondary-container': s => s.onSecondaryContainer,
  tertiary: s => s.tertiary, 'on-tertiary': s => s.onTertiary,
  'tertiary-container': s => s.tertiaryContainer, 'on-tertiary-container': s => s.onTertiaryContainer,
  error: s => s.error, 'on-error': s => s.onError,
  'error-container': s => s.errorContainer, 'on-error-container': s => s.onErrorContainer,
  surface: s => s.surface, 'on-surface': s => s.onSurface,
  'on-surface-variant': s => s.onSurfaceVariant,
  'surface-container-lowest': s => s.surfaceContainerLowest,
  'surface-container-low': s => s.surfaceContainerLow,
  'surface-container': s => s.surfaceContainer,
  'surface-container-high': s => s.surfaceContainerHigh,
  'surface-container-highest': s => s.surfaceContainerHighest,
  outline: s => s.outline, 'outline-variant': s => s.outlineVariant,
  'inverse-surface': s => s.inverseSurface, 'inverse-on-surface': s => s.inverseOnSurface,
  'inverse-primary': s => s.inversePrimary,
};

// Heatmap ramp for the ratings grid: one hue (the theme's), light -> dark for low -> high
// ratings in light mode, and dark -> light in dark mode. Text on each step is whichever
// of near-black / near-white has the better WCAG contrast.
const HEAT_TONES = { light: [95, 89, 81, 72, 63, 47, 38, 29], dark: [22, 28, 36, 44, 57, 66, 75, 85] };
const lum = hex => {
  const c = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16) / 255).map(v => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };

const themes = {};
for (const [name, hex] of Object.entries(SEEDS)) {
  const hct = Hct.fromInt(argbFromHex(hex));
  themes[name] = { seed: hex, light: {}, dark: {} };
  const heatPal = TonalPalette.fromHueAndChroma(hct.hue, Math.max(48, hct.chroma));
  for (const mode of ['light', 'dark']) {
    const scheme = new SchemeTonalSpot(hct, mode === 'dark', 0);
    for (const [role, get] of Object.entries(ROLES)) {
      themes[name][mode][role] = hexFromArgb(get(scheme));
    }
    const dark = hexFromArgb(heatPal.tone(10)), light = hexFromArgb(heatPal.tone(99));
    themes[name][mode].heat = HEAT_TONES[mode].map(t => {
      const bg = hexFromArgb(heatPal.tone(t));
      const fg = contrast(bg, dark) >= contrast(bg, light) ? dark : light;
      return [bg, fg, +Math.max(contrast(bg, dark), contrast(bg, light)).toFixed(2)];
    });
  }
}

// Show colors: harmonized toward each seed's primary so they sit nicely in any theme.
const shows = {};
for (const [seedName, seedHex] of Object.entries(SEEDS)) {
  shows[seedName] = {};
  for (const [show, hex] of Object.entries(SHOWS)) {
    // Kept unharmonized so 11 series stay distinguishable.
    const pal = TonalPalette.fromInt(argbFromHex(hex));
    shows[seedName][show] = {
      light: { c: hexFromArgb(pal.tone(40)), cc: hexFromArgb(pal.tone(90)), occ: hexFromArgb(pal.tone(10)) },
      dark: { c: hexFromArgb(pal.tone(80)), cc: hexFromArgb(pal.tone(30)), occ: hexFromArgb(pal.tone(90)) },
    };
  }
}

const out = `// Generated by scripts/gen-theme.mjs using @material/material-color-utilities. Do not edit by hand.
export const THEMES = ${JSON.stringify(themes)};
export const SHOW_COLORS = ${JSON.stringify(shows)};
`;
writeFileSync(new URL('../js/theme-data.js', import.meta.url), out);
console.log('ok', Object.keys(themes).length, 'themes', (out.length / 1024).toFixed(1), 'KB');
